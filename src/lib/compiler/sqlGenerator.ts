import {
  DATA_TYPES,
  type CompilationResult,
  type ERGraph,
  type RelationalSchema,
} from "../ast/types";
import { validateGraph } from "../ast/schemaValidator";
import { erToRelational, quote } from "./erToRelational";
/** All identifiers are quoted, data types/operators/actions are allowlisted. FKs are
 * emitted after tables, so self-references and mutually dependent tables work. */
export function generateSQL(schema: RelationalSchema): string {
  for (const t of schema.tables)
    for (const c of t.columns)
      if (!DATA_TYPES.includes(c.type)) throw Error("Unsupported SQL type");
  const statements = ["-- Generated by ER Studio · PostgreSQL\nBEGIN;"];
  for (const t of schema.tables) {
    const lines = t.columns.map(
      (c) => `  ${quote(c.name)} ${c.type}${c.nullable ? "" : " NOT NULL"}`,
    );
    lines.push(`  PRIMARY KEY (${t.primaryKey.map(quote).join(", ")})`);
    for (const u of t.uniqueConstraints)
      lines.push(`  UNIQUE (${u.map(quote).join(", ")})`);
    for (const c of t.checks) lines.push(`  CHECK (${c})`);
    statements.push(
      `CREATE TABLE ${quote(t.name)} (\n${lines.join(",\n")}\n);`,
    );
  }
  const usedNames = new Set(schema.tables.map((t) => t.name));
  let index = 0;
  for (const t of schema.tables)
    for (const f of t.foreignKeys) {
      if (
        !["CASCADE", "RESTRICT", "NO ACTION", "SET NULL"].includes(
          f.onDelete,
        ) ||
        !["CASCADE", "RESTRICT", "NO ACTION", "SET NULL"].includes(f.onUpdate)
      )
        throw Error("Invalid referential action");
      statements.push(
        `ALTER TABLE ${quote(t.name)} ADD CONSTRAINT ${quote(f.name)}\n  FOREIGN KEY (${f.columns.map(quote).join(", ")}) REFERENCES ${quote(f.referencedTable)} (${f.referencedColumns.map(quote).join(", ")}) MATCH FULL\n  ON DELETE ${f.onDelete} ON UPDATE ${f.onUpdate};`,
      );
      let indexName;
      do {
        indexName = "er_fk_index_" + ++index;
      } while (usedNames.has(indexName));
      usedNames.add(indexName);
      statements.push(
        `CREATE INDEX ${quote(indexName)} ON ${quote(t.name)} (${f.columns.map(quote).join(", ")});`,
      );
    }
  // Bounded occupancy slots use UNIQUE constraints, so concurrent writes cannot
  // exceed a limit. A conflicting concurrent allocation is rejected and retriable.
  let boundIndex = 0;
  for (const t of schema.tables)
    for (const b of t.boundedCardinalities ?? []) {
      if (!Number.isSafeInteger(b.max) || b.max < 2 || b.max > 1000000)
        throw Error("Invalid cardinality bound");
      const suffix = ++boundIndex;
      let name = `er_bound_${suffix}`;
      while (usedNames.has(name)) name += "_";
      usedNames.add(name);
      const fn = quote(name),
        slot = quote(b.slot);
      let delimiter = "$er_bound$";
      while (JSON.stringify(t).includes(delimiter))
        delimiter = delimiter.slice(0, -1) + "_$";
      const nulls = b.columns
        .map((c) => `NEW.${quote(c)} IS NULL`)
        .join(" OR ");
      const same = b.columns
        .map((c) => `NEW.${quote(c)} IS NOT DISTINCT FROM OLD.${quote(c)}`)
        .join(" AND ");
      const match = b.columns
        .map((c) => `existing.${quote(c)} = NEW.${quote(c)}`)
        .join(" AND ");
      statements.push(`-- Upper bound ${b.max}. Retry a conflicting concurrent allocation.
CREATE FUNCTION ${fn}() RETURNS trigger LANGUAGE plpgsql AS ${delimiter}
BEGIN
  IF ${nulls} THEN NEW.${slot} := NULL; RETURN NEW; END IF;
  IF TG_OP = 'UPDATE' THEN
    IF ${same} THEN NEW.${slot} := OLD.${slot}; RETURN NEW; END IF;
  END IF;
  SELECT candidate INTO NEW.${slot} FROM generate_series(1, ${b.max}) AS candidate
  WHERE NOT EXISTS (SELECT 1 FROM ${quote(t.name)} existing WHERE ${match} AND existing.${slot} = candidate)
  ORDER BY candidate LIMIT 1;
  IF NEW.${slot} IS NULL THEN RAISE EXCEPTION 'Relationship maximum exceeded' USING ERRCODE = '23514'; END IF;
  RETURN NEW;
END;
${delimiter};
CREATE TRIGGER ${fn} BEFORE INSERT OR UPDATE ON ${quote(t.name)} FOR EACH ROW EXECUTE FUNCTION ${fn}();`);
    }
  statements.push("COMMIT;");
  return statements.join("\n\n") + "\n";
}
export function compileGraph(graph: ERGraph): CompilationResult {
  const issues = validateGraph(graph);
  const empty = { tables: [], warnings: [] };
  if (issues.some((i) => i.severity === "error"))
    return { schema: empty, sql: "", issues };
  try {
    const schema = erToRelational(graph);
    return {
      schema,
      sql: generateSQL(schema),
      issues: [
        ...issues,
        ...schema.warnings.map((message) => ({
          severity: "warning" as const,
          code: "CROSS_ROW_CONSTRAINT",
          message,
        })),
      ],
    };
  } catch (e) {
    return {
      schema: empty,
      sql: "",
      issues: [
        ...issues,
        {
          severity: "error",
          code: "COMPILATION",
          message: e instanceof Error ? e.message : "Compilation failed",
        },
      ],
    };
  }
}
